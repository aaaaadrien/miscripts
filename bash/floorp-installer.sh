#! /usr/bin/bash

DOWNLOAD_URL=$(curl -s https://api.github.com/repos/Floorp-Projects/Floorp/releases/latest | grep --color=no -Eo "https.*floorp-linux.*$(uname -m)\.tar\.xz")
ARCHIVE_NAME=$(echo $DOWNLOAD_URL | grep --color=no -Eo "floorp-linux.*$(uname -m)\.tar\.xz")
ICON_NAME="/opt/floorp/floorp.png"
FLOORP_DIR="/opt/floorp/"
DESKTOP_NAME="/usr/local/share/applications/floorp.desktop"
TMP_DIR="/var/tmp"

display_help() {
    echo "Usage: $0 [-i | -u | -r]"
    echo "  -i : Install Floorp"
    echo "  -u : Update Floorp"
    echo "  -r : Remove Floorp"
    exit 0
}

install_floorp() {
    echo "Download Floorp $ARCHIVE_NAME"
    curl -fL "$DOWNLOAD_URL" -o "$TMP_DIR/$ARCHIVE_NAME"

    echo "Extract Floorp $ARCHIVE_NAME"
    tar -xf "$TMP_DIR/$ARCHIVE_NAME" -C "$FLOORP_DIR" --strip-components=1 && rm -f "$TMP_DIR/$ARCHIVE_NAME"

    echo "Icon creation"
    generate_png

    echo "Desktop file creation"
    generate_desktop

}

remove_floorp() {
    rm -rfv "$FLOORP_DIR"
    rm -fv "$DESKTOP_NAME"
}

generate_desktop() {
cat << EOF > "$DESKTOP_NAME"
[Desktop Entry]
Version=1.0
Name=Floorp
GenericName=Web Browser
GenericName[fr]=Navigateur Web
Comment=Browse the Web
Comment[fr]=Navigue sur Internet
Exec=env LD_LIBRARY_PATH="${FLOORP_DIR}/" ${FLOORP_DIR}/floorp %u
Icon=${ICON_NAME}
Terminal=false
Type=Application
MimeType=text/html;text/xml;application/xhtml+xml;application/vnd.mozilla.xul+xml;text/mml;x-scheme-handler/http;x-scheme-handler/https;
Categories=Network;WebBrowser;
Keywords=web;browser;internet;
Actions=new-window;new-private-window;profile-manager-window;

[Desktop Action new-window]
Name=Open a New Window
Name[fr]=Nouvelle fenêtre
Exec=${FLOORP_DIR}/floorp --class="floorp" --new-window %u

[Desktop Action new-private-window]
Name=Open a New Private Window
Name[fr]=Nouvelle fenêtre de navigation privée
Exec=${FLOORP_DIR}/floorp --class="floorp" --private-window %u

[Desktop Action profile-manager-window]
Name=Open the Profile Manager
Exec=${FLOORP_DIR}/floorp --class="floorp" --ProfileManager %u
EOF
}

